#!/usr/bin/env python3
"""Generate src/common/entity/ai/brain/GeneratedMemoryModules.{hpp,cpp}
from MC's MemoryModuleType.java.

MC declares ~90 typed memory keys — `MemoryModuleType<WalkTarget> WALK_TARGET`,
`MemoryModuleType<Boolean> IS_PANICKING` — and every behaviour reads and writes
them by identity. This port cannot use Java's generics for the key type, so the
key becomes an enum and the VALUE becomes a variant; the enum's declared value
kind is generated alongside so `SetMemory` can reject a WalkTarget written into
a boolean slot instead of silently storing it.

Hand-listing 90 keys would be 90 chances to mistype one, and a mistyped key is
a memory that is written and never read — invisible, because a brain with a
missing memory just does nothing.

    python3 tools/gen_memory_modules.py
"""

import os
import re
import sys

MC = "minecraft_code/decompiled_net/minecraft"
SRC = os.path.join(MC, "world/entity/ai/memory/MemoryModuleType.java")
OUT_HPP = "src/common/entity/ai/brain/GeneratedMemoryModules.hpp"
OUT_CPP = "src/common/entity/ai/brain/GeneratedMemoryModules.cpp"

# MC's Java value type -> the alternative it takes in MemoryValue.
#
# Several MC types collapse here on purpose: GlobalPos is a BlockPos plus a
# dimension and this port has one dimension per level, and every concrete
# entity type (Player, Hoglin, AgeableMob…) is stored as the same Entity
# pointer because the behaviour that reads it already knows what it asked for.
KIND = {
    "Void": "Unit", "Unit": "Unit",
    "Boolean": "Bool",
    "Integer": "Int",
    "Long": "Long",
    "Float": "Float",
    "BlockPos": "BlockPos", "GlobalPos": "BlockPos",
    "Vec3": "Vec3",
    "WalkTarget": "WalkTarget",
    "PositionTracker": "PositionTracker",
    "Path": "Path",
    "NearestVisibleLivingEntities": "VisibleEntities",
    "List": "EntityList", "Set": "EntityList",
    "UUID": "Unit",          # only used for owner ids, which this port has not got
    "DamageSource": "Unit",  # HURT_BY: the source itself is not modelled
}
# Anything else that is an entity class.
ENTITY_FALLBACK = "Entity"

DECL = re.compile(r"public static final MemoryModuleType<([^;]*?)>\s+([A-Z_0-9]+)\s*;")


def snake_to_camel(name):
    return "".join(p.capitalize() for p in name.split("_"))


def value_kind(java_type):
    head = java_type.split("<")[0].strip()
    if head in KIND:
        return KIND[head]
    # SpearAttack.SpearStatus and friends — an enum, stored as an int.
    if "." in head:
        return "Int"
    return ENTITY_FALLBACK


def main():
    src = open(SRC, encoding="utf-8").read()
    rows = []
    for m in DECL.finditer(src):
        java_type, const = m.group(1).strip(), m.group(2)
        rows.append((const, snake_to_camel(const), value_kind(java_type), java_type))

    if not rows:
        raise SystemExit("no memory modules parsed — MemoryModuleType.java changed shape")

    enum_rows = ["        %s,%s" % (cpp, ("".ljust(max(1, 30 - len(cpp))) + "// " + java))
                 for _, cpp, _, java in rows]
    kind_rows = ['    MemoryKind::%s,%s// %s' % (
        kind, "".ljust(max(1, 18 - len(kind))), const) for const, _, kind, _ in rows]
    name_rows = ['    "%s",' % const.lower() for const, _, _, _ in rows]

    hpp = """// GENERATED by tools/gen_memory_modules.py — do not edit by hand.
//
// MC net.minecraft.world.entity.ai.memory.MemoryModuleType, as an enum plus a
// declared value kind. The comment on each row is MC's own generic parameter,
// so the mapping from `MemoryModuleType<WalkTarget>` to a variant alternative
// stays checkable by eye.
#pragma once

#include <cstdint>
#include <string_view>

namespace Game {

    // Which alternative of MemoryValue a module stores. Checked on every write:
    // a behaviour that puts the wrong type in a memory would otherwise store it
    // happily and the reader would find nothing, which looks like a brain that
    // simply does not work.
    enum class MemoryKind : uint8_t {
        Unit, Bool, Int, Long, Float, BlockPos, Vec3,
        WalkTarget, PositionTracker, Path, VisibleEntities, EntityList, Entity,
    };

    enum class MemoryModule : uint16_t {
%s
        Count,
    };

    inline constexpr int kMemoryModuleCount = static_cast<int>(MemoryModule::Count);

    MemoryKind       MemoryModuleKind(MemoryModule m);
    std::string_view MemoryModuleName(MemoryModule m);

} // namespace Game
""" % "\n".join(enum_rows)

    cpp = "\n".join([
        "// GENERATED by tools/gen_memory_modules.py — do not edit by hand.",
        '#include "common/entity/ai/brain/GeneratedMemoryModules.hpp"',
        "",
        "namespace Game {",
        "",
        "    namespace {",
        "        const MemoryKind kKinds[kMemoryModuleCount] = {",
        *["    " + r for r in kind_rows],
        "        };",
        "",
        "        const std::string_view kNames[kMemoryModuleCount] = {",
        *["    " + r for r in name_rows],
        "        };",
        "    }",
        "",
        "    MemoryKind MemoryModuleKind(MemoryModule m) {",
        "        return kKinds[static_cast<int>(m)];",
        "    }",
        "",
        "    std::string_view MemoryModuleName(MemoryModule m) {",
        "        return kNames[static_cast<int>(m)];",
        "    }",
        "",
        "} // namespace Game",
        "",
    ])

    os.makedirs(os.path.dirname(OUT_HPP), exist_ok=True)
    open(OUT_HPP, "w", encoding="utf-8").write(hpp)
    open(OUT_CPP, "w", encoding="utf-8").write(cpp)

    kinds = {}
    for _, _, k, _ in rows:
        kinds[k] = kinds.get(k, 0) + 1
    print("%s: %d memory modules" % (OUT_HPP, len(rows)))
    print("  by value kind:", ", ".join(
        "%s=%d" % kv for kv in sorted(kinds.items(), key=lambda x: -x[1])))


if __name__ == "__main__":
    main()
