#!/usr/bin/env python3
"""Generate src/common/world/block/GeneratedLegacySolid.inc from MC's Blocks.java.

MC BlockStateBase.isSolid() is the "legacySolid" flag calculateSolid() caches
per state:

    forceSolidOn  -> true
    forceSolidOff -> false
    else          -> the COLLISION shape's bounds: average side >= 0.7291666…
                     or height >= 1

The shape half is computed at runtime from the engine's collision shapes
(Game::IsLegacySolid). The FORCE half is a Properties flag, and Properties are
copied between blocks (ofLegacyCopy / ofFullCopy carry forceSolidOn/Off) and
built inside helper methods (registerWall, shulkerBoxProperties), so a plain
grep for forceSolidOn() misses most of the blocks that have it. This follows
those copies and helpers.

    python3 tools/gen_legacy_solid.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "minecraft_code_26.3-pre-2/decompiled_net/minecraft/world/level/block/Blocks.java")
OUT = os.path.join(ROOT, "src/common/world/block/GeneratedLegacySolid.inc")


def main():
    text = open(SRC, encoding="utf-8").read()

    # Helper methods whose returned Properties (or registered block) carry a
    # force flag: `static X name(...) { ... forceSolidOn() ... }`.
    helpers = {}
    for m in re.finditer(r"(?:private|public|protected) static [\w<>.?, ]+? (\w+)\(([^)]*)\) \{(.*?)\n   \}", text, re.S):
        body = m.group(3)
        if "forceSolidOn()" in body:
            helpers[m.group(1)] = "on"
        elif "forceSolidOff()" in body:
            helpers[m.group(1)] = "off"

    # Every `NAME = <expr>;` statement of the static initializer, cut at the
    # `;` that closes it — found by balancing brackets, since a lambda body
    # inside the call has `;`s of its own.
    statements = []
    for m in re.finditer(r"^\s*([A-Z][A-Z0-9_]*) = ", text, re.M):
        depth = 0
        i = m.end()
        while i < len(text):
            c = text[i]
            if c in "({[":
                depth += 1
            elif c in ")}]":
                depth -= 1
            elif c == ";" and depth == 0:
                break
            i += 1
        statements.append((m.group(1), text[m.end():i]))

    def flag_of(expr, known):
        flag = None
        # A copy first: its flag is the base's, unless this statement then
        # sets one of its own (applied after the copy, so it wins).
        copy = re.search(r"of(?:Legacy|Full)Copy\(\s*([A-Z][A-Z0-9_]*)\s*\)", expr)
        if copy and copy.group(1) in known:
            flag = known[copy.group(1)]
        for helper, value in helpers.items():
            if re.search(r"\b" + re.escape(helper) + r"\(", expr):
                flag = value
        if "forceSolidOn()" in expr:
            flag = "on"
        elif "forceSolidOff()" in expr:
            flag = "off"
        return flag

    # MC's DyeColor order, and the four copper weathering stages (each also
    # waxed) — how ColorCollection / WeatheringCopperCollection name the
    # blocks they register.
    colors = ["white", "orange", "magenta", "light_blue", "yellow", "lime", "pink", "gray",
              "light_gray", "cyan", "purple", "blue", "brown", "green", "red", "black"]
    stages = ["", "exposed_", "weathered_", "oxidized_"]

    flags = {}
    for name, expr in statements:
        if not expr.lstrip().startswith(("register", "ColorCollection.registerBlocks",
                                         "WeatheringCopperCollection.registerBlocks")):
            continue
        flag = flag_of(expr, flags)
        if not flag:
            continue
        slug = name.lower()
        if expr.lstrip().startswith("ColorCollection.registerBlocks"):
            base = slug[len("dyed_"):] if slug.startswith("dyed_") else slug
            for color in colors:
                flags[f"{color}_{base}".upper()] = flag
        elif expr.lstrip().startswith("WeatheringCopperCollection.registerBlocks"):
            for stage in stages:
                flags[f"{stage}{slug}".upper()] = flag
                flags[f"waxed_{stage}{slug}".upper()] = flag
        else:
            flags[name] = flag

    on = sorted(n.lower() for n, f in flags.items() if f == "on")
    off = sorted(n.lower() for n, f in flags.items() if f == "off")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/gen_legacy_solid.py — do not edit by hand.\n")
        f.write("//\n")
        f.write("// MC Blocks.java's forceSolidOn / forceSolidOff blocks (Properties\n")
        f.write("// copies and helpers followed). LEGACY_SOLID(slug, forced) — forced is\n")
        f.write("// true for forceSolidOn, false for forceSolidOff.\n")
        for slug in on:
            f.write(f'LEGACY_SOLID("{slug}", true)\n')
        for slug in off:
            f.write(f'LEGACY_SOLID("{slug}", false)\n')
    print(f"{len(on)} forceSolidOn, {len(off)} forceSolidOff -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
