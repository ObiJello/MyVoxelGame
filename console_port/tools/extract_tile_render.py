#!/usr/bin/env python3
"""Extract TileRenderer's shape methods: ported/TileRender.cpp.

Copies the listed methods unchanged from
source_full/Minecraft.Client/TileRenderer.cpp into a file that compiles
against src/TileRender.h (namespace console::tile_render), whose Tesselator
collects the quads for the terrain mesh.

Run with --check to fail when the generated file differs from the source.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'source_full/Minecraft.Client/TileRenderer.cpp'
OUT = ROOT / 'ported/TileRender.cpp'
METHODS = ['TileRenderer::tesselateFireInWorld', 'TileRenderer::tesselateTorchInWorld',
           'TileRenderer::tesselateTorch']


def method(text, name):
    matches = list(re.finditer(r'^\S[^\n]*\b' + re.escape(name) + r'\s*\(', text, re.M))
    if len(matches) != 1:
        raise SystemExit(f'{name}: {len(matches)} definitions')
    start = text.rindex('\n', 0, matches[0].start()) + 1
    opening = text.index('{', matches[0].end())
    depth, end = 0, opening
    while True:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
        if depth == 0:
            return text[start:end]


def expected():
    text = SRC.read_text(encoding='utf-8-sig', errors='strict').replace('\r\n', '\n')
    return ('// Generated by tools/extract_tile_render.py: TileRenderer shape methods,\n'
            '// copied unchanged from source_full/Minecraft.Client/TileRenderer.cpp. Do not edit by hand.\n'
            '#include "TileRender.h"\n\nnamespace console::tile_render {\n\n'
            + '\n\n'.join(method(text, name) for name in METHODS) + '\n\n}\n')


def main():
    text = expected()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit('ported/TileRender.cpp is out of date: run tools/extract_tile_render.py')
        print('ported/TileRender.cpp matches the source')
    else:
        OUT.write_text(text)
        print('extracted ported/TileRender.cpp')


if __name__ == '__main__':
    main()
