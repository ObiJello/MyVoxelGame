#pragma once
#include <array>
#include <vector>
namespace console {
// One recipe as the console crafting menu sees it: Recipy::INGREDIENTS_REQUIRED
// (ingredient id, aux and count, 2x2 or 3x3) plus the result and the
// Recipy::eGroupType tab. The console menu is ingredient based; `grid` is the
// original 3x3 layout (id | aux<<24) the menu uses to draw the pattern.
struct CraftingIngredient { int id=0,damage=-1,count=1; }; // damage -1: Recipes::ANY_AUX_VALUE
struct CraftingRecipe {
    int id=0,count=1,damage=0;
    std::vector<CraftingIngredient> ingredients;
    bool needsTable=false; // RECIPE_TYPE_3x3
    const char* group="";
    std::array<unsigned,9> grid{};
};
// Generated by tools/extract_recipes.py from the original Recipes.cpp and its
// ToolRecipies/WeaponRecipies/FoodRecipies/OreRecipies/StructureRecipies/
// ArmorRecipes/ClothDyeRecipes tables, in registration (menu) order.
const std::vector<CraftingRecipe>& consoleCraftingRecipes();
// Item::setCraftingRemainingItem: water, lava and milk buckets leave a bucket.
int consoleCraftingRemainingItem(int id);
}
